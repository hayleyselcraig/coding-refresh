## Warmup exercise for more practice with functions.
## Create a function which takes a name and returns a greeting.
## Print the returned greeting outside the function.

def greet_user(name):
    greeting = (f"Hello {name}, hope your having a good day!")
    return greeting

print(greet_user("hayley"))
print(greet_user("Sammy"))
print(greet_user("Ryan"))